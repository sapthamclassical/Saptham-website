#!/usr/bin/env node
/**
 * Concatenates the migrations + seed into supabase/apply_all.sql so the whole
 * backend can be applied with a single paste into the Supabase SQL Editor.
 *
 *   node scripts/bundle-sql.mjs
 *
 * Generated — never edit apply_all.sql by hand.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = resolve(root, "supabase/migrations");
const seedDir = resolve(root, "supabase/seed");

const parts = [
  "-- ============================================================================",
  "-- Saptham CMS — FULL BACKEND BUNDLE",
  "-- GENERATED by scripts/bundle-sql.mjs — do not edit.",
  "-- Paste this whole file into the Supabase SQL Editor and Run.",
  "-- Safe to re-run (every statement is idempotent / upserting).",
  "-- ============================================================================",
  "",
];

// Order matters: schema → RLS → seed → storage. Storage goes LAST because it
// touches storage.objects (owned by supabase_storage_admin) and is the step most
// likely to hit a permission error; by then everything else has already run.
const isStorage = (f) => /storage/i.test(f);
const migrations = readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort();
const seeds = existsSync(seedDir)
  ? readdirSync(seedDir).filter((f) => f.endsWith(".sql")).sort()
  : [];

const files = [
  ...migrations.filter((f) => !isStorage(f)).map((f) => join(migrationsDir, f)),
  ...seeds.map((f) => join(seedDir, f)),
  ...migrations.filter(isStorage).map((f) => join(migrationsDir, f)),
];

for (const file of files) {
  const rel = file.replace(root, "").replace(/\\/g, "/").replace(/^\//, "");
  parts.push(`\n-- ${"=".repeat(74)}`);
  parts.push(`-- BEGIN ${rel}`);
  parts.push(`-- ${"=".repeat(74)}\n`);
  parts.push(readFileSync(file, "utf8").trimEnd());
  parts.push(`\n-- END ${rel}\n`);
}

writeFileSync(resolve(root, "supabase/apply_all.sql"), parts.join("\n"), "utf8");
console.log(`✓ bundled ${files.length} file(s) → supabase/apply_all.sql`);
files.forEach((f) => console.log("   ·", f.replace(root, "").replace(/\\/g, "/").replace(/^\//, "")));
